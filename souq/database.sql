CREATE DATABASE IF NOT EXISTS souq CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE souq;

CREATE TABLE IF NOT EXISTS admins (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS products (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  cat VARCHAR(64) NOT NULL,
  cond_type ENUM('new','used','refurb') NOT NULL DEFAULT 'new',
  price DECIMAL(10,2) NOT NULL,
  description TEXT NULL,
  img VARCHAR(255) NULL,
  available TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (created_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS orders (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  product_id INT UNSIGNED NULL,
  product_name VARCHAR(255) NOT NULL,
  price DECIMAL(10,2) NOT NULL,
  name VARCHAR(255) NOT NULL,
  phone CHAR(11) NOT NULL,
  alt_phone CHAR(11) NOT NULL,
  gov VARCHAR(64) NOT NULL,
  city VARCHAR(120) NOT NULL,
  address TEXT NOT NULL,
  pay ENUM('instapay','vodafone') NOT NULL,
  pay_to VARCHAR(100) NOT NULL,
  receipt_file VARCHAR(255) NULL,
  done TINYINT(1) NOT NULL DEFAULT 0,
  ip VARCHAR(45) NOT NULL DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (created_at),
  INDEX (ip, created_at),
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE SET NULL
) ENGINE=InnoDB;
